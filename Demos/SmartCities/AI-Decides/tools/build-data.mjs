// Builds the compact data files of the AI-Decides demo from the GTFS-Madrid-Bench CHANGE packages (base version).
//   node tools/build-data.mjs <dir with base-1-*.csv> <dir with base-10-*.csv>
// Packages: Van Assche et al., Zenodo 10.5281/zenodo.14038823 (GTFS-Scale-1-CHANGE, GTFS-Scale-10-CHANGE), data/shared/.
// Kept: ROUTES (route_id), TRIPS (route_id, service_id, trip_id, direction_id), FREQUENCIES (headway_secs, in file order
// per trip), STOP_TIMES (count per trip), CALENDAR (day flags). Nothing is invented here; ids stay as in the feed.
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "data");
const csv = (f) => { const [h, ...rows] = readFileSync(f, "utf8").replace(/^\uFEFF/, "").trim().split(/\r?\n/); const k = h.split(",");
  return rows.map((r) => { const v = r.split(","); const o = {}; k.forEach((x, i) => (o[x] = v[i])); return o; }); };
function build(dir, scale) {
  const T = (t) => csv(join(dir, `base-${scale}-${t}.csv`));
  const routes = T("ROUTES"), trips = T("TRIPS"), freq = T("FREQUENCIES"), st = T("STOP_TIMES"), cal = T("CALENDAR"), cd = T("CALENDAR_DATES");
  const D = ["monday", "tuesday", "wednesday", "thursday", "friday", "saturday", "sunday"];
  const sIx = new Map(cal.map((c, i) => [c.service_id, i + 1]));
  const byTrip = new Map(); freq.forEach((f) => { if (!byTrip.has(f.trip_id)) byTrip.set(f.trip_id, []); byTrip.get(f.trip_id).push(+f.headway_secs); });
  const stN = new Map(); st.forEach((s) => stN.set(s.trip_id, (stN.get(s.trip_id) || 0) + 1));
  const R = routes.map((r) => ({ id: r.route_id, type: +r.route_type, trips: [] })), rIx = new Map(routes.map((r, i) => [r.route_id, i]));
  let skipped = 0;
  trips.forEach((t) => { const r = rIx.get(t.route_id), s = sIx.get(t.service_id); if (r == null || !s) { skipped++; return; }
    R[r].trips.push({ id: t.trip_id, s, dir: +t.direction_id || 0, st: stN.get(t.trip_id) || 0, h: byTrip.get(t.trip_id) || [] }); });
  const counts = { routes: routes.length, trips: trips.length, frequencies: freq.length, stop_times: st.length, calendar: cal.length, calendar_dates: cd.length, tripsSkipped: skipped };
  const out = { v: 1, scale, generated: true,
    source: `GTFS-Madrid-Bench (Van Assche et al.), Zenodo 10.5281/zenodo.14038823, GTFS-Scale-${scale}-CHANGE, base version. Generated by the benchmark's VIG generator from Madrid Metro's feed: ids, names and clock times are encoded; headway_secs, day flags and stop_times membership are usable.`,
    counts, services: cal.map((c) => ({ id: c.service_id, days: D.map((d) => c[d]).join("") })), routes: R };
  const file = join(OUT, `madrid-s${scale}.json`); writeFileSync(file, JSON.stringify(out));
  console.log(file, JSON.stringify(counts), (readFileSync(file).length / 1024).toFixed(1) + " KB");
}
build(process.argv[2], 1); build(process.argv[3], 10);
